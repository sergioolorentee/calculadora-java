package programacion_1gs.capitulo1;

public class Variables {

    public static void main(String[] args){
        int numero = 20;
        int numero2 = 5;

        int sumar = numero+numero2;
        int restar = numero-numero2;
        int dividir = numero/numero2;
        int multiplicar = numero*numero2;
        System.out.println("La suma es: " + sumar);
        System.out.println("La resta es: " + restar);
        System.out.println("La división es: " + dividir);
        System.out.println("La multiplicación es:  " + multiplicar);

    }
}

